static uint8_t cur_col = 0;
static uint8_t cur_row = 0;

/* Установка позиции в RAM дисплея: X в пикселях, Y - номер банка */
void lcd_set_xy(uint8_t x, uint8_t bank)
{
    uint8_t cmd[] = {
        TIC32AN_CONTROL_CMD, 0x01,                                  /* H[1:0] = 00: function and RAM command page */
        TIC32AN_CONTROL_CMD, (uint8_t)(0x40U | (bank + LCD_Y_OFFSET)), /* Y */
        TIC32AN_CONTROL_CMD, (uint8_t)(0x80U | x)                   /* X */
    };
    i2c_transmit(I2C0_SLAVE_ADDRESS7, cmd, sizeof(cmd));
}

void lcd_set_cursor(uint8_t col, uint8_t row)
{
    if(col >= LCD_COLS || row >= LCD_ROWS) {
        return;
    }
    cur_col = col;
    cur_row = row;
    lcd_set_xy((uint8_t)(col * FONT_CELL_WIDTH), row);
}

static uint16_t build_glyph(uint8_t *dst, char c)
{
    uint8_t ch = (uint8_t)c;
    if(ch < FONT_FIRST_CHAR || ch > FONT_LAST_CHAR) {
        ch = '?';
    }
    for(uint8_t i = 0; i < FONT_WIDTH; ++i) {
        dst[i] = font5x8[ch - FONT_FIRST_CHAR][i];
    }
    dst[FONT_WIDTH] = 0x00; /* интервал */
    return FONT_CELL_WIDTH;
}

void lcd_putc(char c)
{
    uint8_t buf[1U + FONT_CELL_WIDTH];

    if(cur_col >= LCD_COLS) {
        return;
    }
    buf[0] = TIC32AN_CONTROL_DATA;
    build_glyph(&buf[1], c);
    i2c_transmit(I2C0_SLAVE_ADDRESS7, buf, sizeof(buf));
    ++cur_col;
}

void lcd_puts(uint8_t col, uint8_t row, const char *s)
{
    uint8_t buf[1U + LCD_COLS * FONT_CELL_WIDTH];
    uint16_t n = 1U;

    if(s == NULL || col >= LCD_COLS || row >= LCD_ROWS) {
        return;
    }

    buf[0] = TIC32AN_CONTROL_DATA;
    while(*s != '\0' && col < LCD_COLS) {
        n += build_glyph(&buf[n], *s++);
        ++col;
    }

    lcd_set_cursor(col - (uint8_t)((n - 1U) / FONT_CELL_WIDTH), row);
    i2c_transmit(I2C0_SLAVE_ADDRESS7, buf, n);
    cur_col = col;
    cur_row = row;
}

void lcd_clear(void)
{
    uint8_t buf[1U + LCD_WIDTH_PX] = {0};

    buf[0] = TIC32AN_CONTROL_DATA;
    for(uint8_t row = 0; row < LCD_ROWS; ++row) {
        lcd_set_xy(0, row);
        i2c_transmit(I2C0_SLAVE_ADDRESS7, buf, sizeof(buf));
    }
    lcd_set_cursor(0, 0);
}

