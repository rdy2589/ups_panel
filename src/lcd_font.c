/* Найти глиф; неизвестный символ -> пустой (пробел, индекс 0) */
static const uint8_t *font16_rows(char c)
{
    for(uint8_t i = 0; i < FONT16_COUNT; ++i) {
        if(font16[i].ch == c) {
            return font16[i].rows;
        }
    }
    return font16[0].rows;
}

/* Вывод строки шрифтом 8x16.
   col: 0..15 (ячейка 8 точек), row: 0..2 (номер верхнего банка; строка
   занимает банки row и row+1). Строка обрезается по краю дисплея.
   Хвост предыдущего текста не стирается - добивайте строку пробелами. */
void lcd_puts16(uint8_t col, uint8_t row, const char *s)
{
    uint8_t buf[1U + LCD_COLS16 * FONT16_CELL_WIDTH];

    if(s == NULL || col >= LCD_COLS16 || row > (LCD_ROWS - 2U)) {
        return;
    }

    for(uint8_t half = 0; half < 2U; ++half) {
        uint16_t n = 1U;
        uint8_t c = col;

        buf[0] = TIC32AN_CONTROL_DATA;
        for(const char *p = s; *p != '\0' && c < LCD_COLS16; ++p, ++c) {
            const uint8_t *r = font16_rows(*p) + (half * 8U);
            for(uint8_t x = 0; x < FONT16_CELL_WIDTH; ++x) {
                uint8_t b = 0;
                for(uint8_t k = 0; k < 8U; ++k) {
                    if((r[k] >> (7U - x)) & 1U) {
                        b |= (uint8_t)(1U << k);
                    }
                }
                buf[n++] = b;
            }
        }
        if(n == 1U) {
            return;
        }
        lcd_set_xy((uint8_t)(col * FONT16_CELL_WIDTH), (uint8_t)(row + half));
        i2c_transmit(I2C0_SLAVE_ADDRESS7, buf, n);
    }
}
